// Плосък списък за търсачката. BROAD_KEYWORDS се включват само при DISCOVERY_BROAD=1,
// защото носят най-много шум (и съответно най-много работа на класификатора).
export const KEYWORDS = KEYWORD_GROUPS.flatMap((g) => g.terms);
export const BROAD_KEYWORDS = KEYWORD_GROUPS.flatMap((g) => g.broad || []);

// Коя дума към коя група принадлежи — за етикета „намерена по“ в имейла.
export const TERM_GROUP = Object.fromEntries(
  KEYWORD_GROUPS.flatMap((g) => [...g.terms, ...(g.broad || [])].map((t) => [t, g.label])),
);

export function activeKeywords() {
  const broad = process.env.DISCOVERY_BROAD === "1";
  return broad ? [...KEYWORDS, ...BROAD_KEYWORDS] : KEYWORDS;
}
